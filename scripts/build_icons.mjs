// Vendor exact icon nodes from the installed Lucide version; no network at runtime.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const mapping={file:'file-text',plus:'plus',save:'save',download:'download',upload:'upload',arrow:'arrow-right',back:'arrow-left',close:'x',shield:'scan-search',chart:'chart-no-axes-combined',network:'network',search:'search',copy:'copy',book:'book-open',chevron:'chevron-right',compare:'git-compare-arrows',focus:'focus',clock:'history',refresh:'refresh-cw'};
const nodes={};
for(const [name,file] of Object.entries(mapping)){
 const code=fs.readFileSync(path.join(root,'frontend/node_modules/lucide-react/dist/esm/icons',file+'.js'),'utf8');
 const match=code.match(/createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\s*\);/);
 if(!match)throw Error('Cannot extract official icon nodes: '+file);
 nodes[name]=vm.runInNewContext(match[1]).map(([tag,attributes])=>[tag,Object.fromEntries(Object.entries(attributes).filter(([key])=>key!=='key'))]);
}
fs.writeFileSync(path.join(root,'app/static/icons.js'),'// Lucide v0.468.0, ISC license. Generated by scripts/build_icons.mjs.\nexport const iconNodes='+JSON.stringify(nodes)+';\n');
fs.copyFileSync(path.join(root,'frontend/node_modules/lucide-react/LICENSE'),path.join(root,'app/static/LUCIDE_LICENSE'));
console.log('Vendored '+Object.keys(nodes).length+' official icons.');
